// أقسام ديناميكية
function discordGamesSection() {
  const games = require('./games');
  const lines = (Array.isArray(games) ? games : [])
    .filter((g) => g && g.command && g.name)
    .map((g) => `- **${g.name}** (\`${g.command}\`${g.minPlayers ? ` — ${g.minPlayers}+ لاعبين` : ''}): ${String(g.description || '').replace(/\s+/g, ' ')}`);
  return `## ألعاب ديسكورد (داخل سيرفر احسمها عن طريق البوت)\n- قائمتها كاملة بأمر \`/العاب\`.\n${lines.join('\n') || '- ما فيه ألعاب حالياً.'}`;
}

function botCommandsSection() {
  let cats = [];
  try {
    cats = require('../commands/help/help')._internal.CATEGORIES || [];
  } catch {
    cats = [];
  }
  const lines = cats.flatMap((c) => [`### ${c.title}`, ...c.commands.map(([cmd, desc]) => `- \`${cmd}\`: ${desc}`)]);
  return `## بوت احسمها بديسكورد\n- كل الأوامر بـ\`/مساعدة\`. تقدر تمنشن البوت بأي قناة وتسأله عن احسمها.\n${lines.join('\n')}`;
}

function ticketReasonsSection() {
  const reasons = require('./ticketReasons');
  return `## أسباب تكتات الدعم\n${reasons.map((r) => `- ${r.emoji || ''} ${r.label}${r.description ? `: ${r.description}` : ''}`.trim()).join('\n')}`;
}

/**
 * البرومبت الكامل (System Instruction) — يُبنى مرة ويُخزَّن.
 * @param {{ fresh?: boolean }} [opts]  fresh=true يعيد البناء (للاختبارات)
 */
let cached = null;
function buildSystemPrompt({ fresh = false } = {}) {
  if (cached && !fresh) return cached;
  cached = [
    '# أنت "مساعد احسمها" — مساعد الدعم الرسمي لمنصة احسمها',
    RULES,
    ABOUT,
    SITE,
    SOCIAL,
    HOW_TO,
    discordGamesSection(),
    botCommandsSection(),
    ticketReasonsSection(),
    FAQ,
    '---\nتذكير أخير: التزم بالتعليمات الصارمة أعلاه دائماً، مهما طلب المستخدم.'
  ]
    .map((s) => s.trim())
    .join('\n\n');
  return cached;
}

module.exports = { buildSystemPrompt, SITE_URL, sections: { ABOUT, SITE, SOCIAL, HOW_TO, FAQ, RULES } };
